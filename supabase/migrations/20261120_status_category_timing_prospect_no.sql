-- 1-1. ステータス：4・6 をなくす
update public.prospects set status = 3 where status = 4;
update public.prospects set status = 5 where status = 6;

-- 1-2. 案件種別：「分析」「工事」を外す
delete from public.prospect_categories where category in ('分析', '工事');

-- 1-3. 受注見込み時期：来年度以降にまとめる
update public.prospects set timing_label = '来年度以降'
where timing_label in ('来年度', '2年以内', '3年以内');

-- 1-4. 案件番号：列を足し、登録順に番号を振ってから、以後は自動で振られるようにする
alter table public.prospects add column if not exists prospect_no bigint;

with numbered as (
  select id, row_number() over (order by created_at, id) as rn
  from public.prospects
)
update public.prospects p set prospect_no = n.rn
from numbered n
where p.id = n.id and p.prospect_no is null;

alter table public.prospects alter column prospect_no set not null;
alter table public.prospects alter column prospect_no add generated by default as identity;
select setval(pg_get_serial_sequence('public.prospects', 'prospect_no'),
              (select max(prospect_no) from public.prospects));

alter table public.prospects
  drop constraint if exists prospects_prospect_no_key,
  add constraint prospects_prospect_no_key unique (prospect_no);

